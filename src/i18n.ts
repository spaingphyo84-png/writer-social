export const dictionaries = { en, my }

export function translate(locale: Locale, key: TranslationKey, vars?: Record<string, string | number>): string {
  const value = dictionaries[locale][key] ?? en[key]
  if (!vars) return value
  return value.replace(/\{(\w+)\}/g, (match, name: string) => String(vars[name] ?? match))
}
